//! The project's own tasks (spec 027): the parameters page, docs/guitarfx/parameters.md, written from the registry
//! (`guitarfx_dsp::params::ENTRIES`) and its English texts, so that the page, the *Advanced* window and the settings reader never differ
//! (FR-019).

use guitarfx_dsp::params::ENTRIES;
use guitarfx_settings::settings::FILE;
use guitarfx_settings::texts::Texts;
use std::path::PathBuf;

/// docs/guitarfx/parameters.md, from the repository's root.
pub fn parameters_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/guitarfx/parameters.md")
}

/// A value as the page writes it: Rust's shortest form (`0.5`, `-1`, `1000`).
pub fn number(value: f64) -> String {
    format!("{value}")
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The whole page.
pub fn parameters_markdown() -> String {
    let texts = Texts::english();
    let mut page = String::new();
    page.push_str("# GuitarFX: the internal values\n\n");
    page.push_str("<!-- Generated by `cargo run -p xtask -- parameters` in guitarfx/ from the registry (guitarfx-dsp/src/params.rs) and the English texts. Do not edit: guitarfx/xtask/tests/parameters_doc.rs fails when this page differs from the registry. -->\n\n");
    page.push_str(&format!(
        "Every internal value of GuitarFX's sound, {} in all. Each can be changed in the *Advanced* window (Defaults puts them all back) or in the file `{FILE}` of the settings folder, as `key=value`; a value outside its range is brought to the nearer bound, and one that is not a number is ignored (the default stays). The reverb's and the echo's steps are lowered when needed, so that every repeat dies away. A change takes effect the next time the sound is turned on; the plugin reads the same file when the host starts it. The defaults are the tested ones; a value TuxGuitarAdvanced's *Amp and effects* also has is the same there.\n\n",
        ENTRIES.len()
    ));
    page.push_str("The settings folder: `~/Library/Application Support/GuitarFX` on macOS, `%APPDATA%\\GuitarFX` on Windows, `~/.config/guitarfx` on Linux (or `$XDG_CONFIG_HOME/guitarfx`).\n");
    let mut category = "";
    for entry in ENTRIES.iter() {
        if entry.category != category {
            category = entry.category;
            page.push_str(&format!("\n## {}\n\n", texts.get(&format!("advanced.category.{category}"))));
            page.push_str("| Key | Name | Unit | Default | Minimum | Maximum | What it does |\n");
            page.push_str("|---|---|---|---:|---:|---:|---|\n");
        }
        let unit = if entry.unit.is_empty() { "" } else { entry.unit };
        page.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} | {} |\n",
            entry.key,
            cell(texts.get(&entry.name_key())),
            cell(unit),
            number(entry.default),
            number(entry.min),
            number(entry.max),
            cell(texts.get(&entry.tooltip_key())),
        ));
    }
    page
}
