//! The registry of GuitarFX's external parameters (spec 027, FR-016, R7): one entry per parameter row of
//! `specs/027-standalone-amp/inventory.md`, with its key, category, unit, bounds and a default equal to the Java literal it replaces. A
//! [`Params`] value is built once, off the audio thread, from the settings' key→value pairs; every element reads its internal values from
//! it, never from a constant. The *Advanced* window, the settings reader and the documentation read the same table.

/// One external parameter.
#[derive(Clone, Copy, Debug)]
pub struct Entry {
    pub id: Id,
    /// `guitarfx.<category>.<name>`
    pub key: &'static str,
    pub category: &'static str,
    pub unit: &'static str,
    pub default: f64,
    pub min: f64,
    pub max: f64,
}

impl Entry {
    /// The text key of its name in the *Advanced* window.
    pub fn name_key(&self) -> String {
        format!("{}.name", self.key)
    }

    /// The text key of its tooltip.
    pub fn tooltip_key(&self) -> String {
        format!("{}.tooltip", self.key)
    }
}

