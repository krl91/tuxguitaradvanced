/// The number of parameters.
pub const COUNT: usize = Id::ReverbAllPass as usize + 1;

/// The highest sum of a feedback and its steps (the reverb's combs, the echo's repeats): under it the tail always decays.
const DECAYING: f64 = 0.99;

/// Every parameter's value, plain numbers with no heap (it is copied into the chain).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Params {
    values: [f64; COUNT],
}

impl Default for Params {
    fn default() -> Self {
        Self::defaults()
    }
}

impl Params {
    /// Every parameter at its default.
    pub fn defaults() -> Self {
        let mut values = [0.0; COUNT];
        for entry in &ENTRIES {
            values[entry.id as usize] = entry.default;
        }
        Self { values }
    }

    /// The defaults, then each known key's value brought into its bounds; a value that is not a number, or an unknown key, is ignored.
    /// The combined bounds of the inventory follow: the steps are lowered so that each sum stays at most 0.99.
    pub fn from_values<'a>(pairs: impl IntoIterator<Item = (&'a str, &'a str)>) -> Self {
        let mut params = Self::defaults();
        for (key, text) in pairs {
            let Some(entry) = ENTRIES.iter().find(|e| e.key == key.trim()) else {
                continue;
            };
            let Ok(value) = text.trim().parse::<f64>() else {
                continue;
            };
            if value.is_nan() {
                continue;
            }
            params.values[entry.id as usize] = value.clamp(entry.min, entry.max);
        }
        let steps = f64::from(crate::knobs::STEPS);
        let feedback = params.get(Id::ReverbFeedback);
        if feedback + steps * params.get(Id::ReverbSizeStep) > DECAYING {
            params.values[Id::ReverbSizeStep as usize] = (DECAYING - feedback) / steps;
        }
        if steps * params.get(Id::EchoRepeatsStep) > DECAYING {
            params.values[Id::EchoRepeatsStep as usize] = DECAYING / steps;
        }
        params
    }

    pub fn get(&self, id: Id) -> f64 {
        self.values[id as usize]
    }

    /// The value of that key, or none for a key the registry does not have.
    pub fn get_key(&self, key: &str) -> Option<f64> {
        ENTRIES.iter().find(|e| e.key == key).map(|e| self.values[e.id as usize])
    }

    /// The parameter's entry.
    pub fn entry(id: Id) -> &'static Entry {
        &ENTRIES[id as usize]
    }
}

